fn main() {
    println("--- Test 1: [4]i32 Array ---")
    let arr: [4]i32 = [1, 2, 3, 4]
    println(arr)

    println("--- Test 2: [4]char Array ---")
    let arr1: [4]char = ['1', '2', '3', '4']
    println(arr1)

    println("--- Test 3: [3]bool Array ---")
    let arr2: [3]bool = [true, false, true]
    println(arr2)

    println("--- Test 4: [3]string Array ---")
    let arr3: [3]string = ["cupid", "fast", "safe"]
    println(arr3)

    println("--- Test 5: [3]f64 Array ---")
    let arr4: [3]f64 = [1.5, 2.75, 3.125]
    println(arr4)
}
